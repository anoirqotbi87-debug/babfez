package app.babfez.conciergerie;

import android.content.pm.ActivityInfo;
import android.net.Uri;
import android.os.Build;
import android.os.Bundle;
import android.view.View;
import android.view.ViewGroup;
import android.webkit.WebView;

public class LauncherActivity
        extends com.google.androidbrowserhelper.trusted.LauncherActivity {

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        // Setting an orientation crashes the app due to the transparent background on Android 8.0
        // Oreo and below. We only set the orientation on Oreo and above. This only affects the
        // splash screen and Chrome will still respect the orientation.
        // See https://github.com/GoogleChromeLabs/bubblewrap/issues/496 for details.
        if (Build.VERSION.SDK_INT > Build.VERSION_CODES.O) {
            setRequestedOrientation(ActivityInfo.SCREEN_ORIENTATION_USER_PORTRAIT);
        } else {
            setRequestedOrientation(ActivityInfo.SCREEN_ORIENTATION_UNSPECIFIED);
        }
    }

    @Override
    protected Uri getLaunchingUrl() {
        return super.getLaunchingUrl();
    }

    /**
     * Interception du bouton Retour physique / geste système Android :
     * Si une WebView est active et possède un historique de navigation (canGoBack()),
     * effectue un retour arrière (goBack()). Sinon, délègue au comportement standard.
     */
    @Override
    public void onBackPressed() {
        View focus = getCurrentFocus();
        if (focus instanceof WebView) {
            WebView wv = (WebView) focus;
            if (wv.canGoBack()) {
                wv.goBack();
                return;
            }
        }

        if (getWindow() != null && getWindow().getDecorView() != null) {
            WebView webView = findWebView(getWindow().getDecorView());
            if (webView != null && webView.canGoBack()) {
                webView.goBack();
                return;
            }
        }

        super.onBackPressed();
    }

    private WebView findWebView(View view) {
        if (view instanceof WebView) {
            return (WebView) view;
        }
        if (view instanceof ViewGroup) {
            ViewGroup group = (ViewGroup) view;
            for (int i = 0; i < group.getChildCount(); i++) {
                WebView found = findWebView(group.getChildAt(i));
                if (found != null) {
                    return found;
                }
            }
        }
        return null;
    }
}
