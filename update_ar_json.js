// ASCII escaping function to safely write the JSON
// `JSON.stringify` alone will output raw utf8 characters (depending on string), 
// but wait, since I'm running Node, JSON.stringify actually writes the exact characters.
// To force ASCII sequences (like \u0644) I can use a replacer!
function escapeUnicode(str) {
  return str.replace(/[^\0-~]/g, function(ch) {
    return "\\u" + ("000" + ch.charCodeAt(0).toString(16)).slice(-4);
  });
}

